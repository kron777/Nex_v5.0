"""source_kind -- per-STREAM provenance, stamped at the write boundary.

beliefs.source names the PRODUCER (the loop that wrote the row). For sense
beliefs that name is one flat bucket, 'precipitated_from_sense', covering every
external stream: a headline she read and a stream she sensed in herself wore
the same name. The stream that produced a sense belief was in hand at
crystallization (sense_events.stream) and then dropped -- and a stream never
recorded can't be reconstructed later.

So every row now carries:
    source_stream  the originating sense stream, when there is one
    source_kind    WHAT KIND of origin, for every row:
        authored    written by her own loop from her own material
        self        her sensing / observing herself (internal.* streams,
                    witness/pattern/identity loops, self-observation)
        seeded      founding material written in on purpose (keystones,
                    identity claims, koans) -- not generated by her
        world       impersonal external data (news wires, prices, arxiv)
        other_mind  text authored by another mind (essays, literature,
                    named-thinker forums, the other_mind persona stream)
        received    anything else not hers (probes, quarantined or rejected
                    content, unknown producers, sense with no stream)

Stamping is a trigger (beliefs_trigger_sql), so EVERY write boundary -- the
distiller, the ~dozens of loops that INSERT INTO beliefs, and any added later --
gets a kind without each producer remembering to. Precedence on insert:
    1. an explicit source_kind the writer passed
    2. the kind of source_stream (the writer's, else INHERITED from an earlier
       row with identical content that has a stream: a verbatim copy of a
       headline is still a headline, whatever loop copied it -- this is the
       class behind counterfactual_node/precipitated_from_sense cross-band rows)
    3. the kind of the producer's name (source)
sense_events gets the same stream->kind stamp at insert, so anything built on
the event stream later (episodic memory) inherits a clean feed.

The Python functions and the SQL renderings share ONE table of rules below;
tests/test_source_kind.py pins that they agree.
"""
from __future__ import annotations

from typing import Optional

KINDS = ("authored", "self", "seeded", "world", "other_mind", "received")

# --- stream -> kind (the rules classify_stream has always applied) ----------
_SELF_STREAM_PREFIXES = ("internal.", "external.self")
_SELF_STREAMS = frozenset({"fountain"})
_OTHER_MIND_STREAM_PREFIXES = ("external.other_mind", "othermind")
# Authored-by-a-mind feeds: literature, essays, named-thinker forums, lab writing.
_OTHER_MIND_STREAMS = frozenset({
    "literature.gutenberg",   # authors (Laozi, the canon)
    "philosophy.aeon",        # essayists
    "cognition.lesswrong",    # named thinkers arguing
    "ai_research.lab_blogs",  # labs writing with intent/voice
})

# --- producer name -> kind ---------------------------------------------------
# Mirrors the bands of affinity_loop.PROVENANCE_BASE (authored -> authored,
# witnessed -> self, received -> world/received); the test pins that every
# mapped source keeps its band.
_KIND_BY_SOURCE: dict[str, str] = {
    **dict.fromkeys((
        "fountain_insight", "synergized", "counterfactual_node", "remember_loop",
        "wonder_loop", "hot_observer", "surprise", "fountain", "emergent_drive",
    ), "authored"),
    **dict.fromkeys((
        "witness_loop", "pattern_loop", "identity_loop", "behavioural_observation",
        "precipitated_from_dynamic", "self_rut_notice", "self_downtime",
    ), "self"),
    **dict.fromkeys((
        "keystone_seed", "identity", "self_location", "koan", "tao", "heart_sutra",
        "reification_recognition", "dont_know",
    ), "seeded"),
    "fetch_loop": "world",
    # precipitated_from_sense is deliberately absent: its kind comes from its
    # stream. With no stream recorded it falls to 'received'.
}
_KIND_BY_SOURCE_PREFIX: dict[str, str] = {
    "grounded_scorecard:": "self",   # her own calls, checked against the world
}
DEFAULT_KIND = "received"


def classify_stream(stream: Optional[str]) -> str:
    """Kind of a sense stream: self | other_mind | world."""
    s = (stream or "").lower()
    if s.startswith(_SELF_STREAM_PREFIXES) or s in _SELF_STREAMS:
        return "self"
    if s.startswith(_OTHER_MIND_STREAM_PREFIXES) or s in _OTHER_MIND_STREAMS:
        return "other_mind"
    return "world"


def kind_for_source(source: Optional[str]) -> str:
    """Kind of a producer name, for rows with no stream."""
    if source in _KIND_BY_SOURCE:
        return _KIND_BY_SOURCE[source]
    for prefix, kind in _KIND_BY_SOURCE_PREFIX.items():
        if (source or "").startswith(prefix):
            return kind
    return DEFAULT_KIND


def kind_for(source: Optional[str], stream: Optional[str] = None) -> str:
    """A row's kind: its stream's when it has one, else its producer's."""
    return classify_stream(stream) if stream else kind_for_source(source)


# --- SQL renderings of the same rules ----------------------------------------

def _lit(s: str) -> str:
    assert "'" not in s, s
    return f"'{s}'"


def _prefix_test(expr: str, prefix: str) -> str:
    # substr, not LIKE: '_' in a LIKE pattern is a wildcard.
    return f"substr({expr}, 1, {len(prefix)}) = {_lit(prefix)}"


def _in_list(expr: str, names) -> str:
    return f"{expr} IN ({', '.join(_lit(n) for n in sorted(names))})"


def stream_kind_sql(expr: str) -> str:
    """SQL CASE equal to classify_stream(<expr>)."""
    s = f"lower(COALESCE({expr}, ''))"
    self_tests = [_prefix_test(s, p) for p in _SELF_STREAM_PREFIXES]
    self_tests.append(_in_list(s, _SELF_STREAMS))
    om_tests = [_prefix_test(s, p) for p in _OTHER_MIND_STREAM_PREFIXES]
    om_tests.append(_in_list(s, _OTHER_MIND_STREAMS))
    return (f"CASE WHEN {' OR '.join(self_tests)} THEN 'self' "
            f"WHEN {' OR '.join(om_tests)} THEN 'other_mind' ELSE 'world' END")


def source_kind_sql(expr: str) -> str:
    """SQL CASE equal to kind_for_source(<expr>)."""
    whens = []
    for kind in KINDS:
        names = [n for n, k in _KIND_BY_SOURCE.items() if k == kind]
        if names:
            whens.append(f"WHEN {_in_list(expr, names)} THEN {_lit(kind)}")
    for prefix, kind in _KIND_BY_SOURCE_PREFIX.items():
        whens.append(f"WHEN {_prefix_test(expr, prefix)} THEN {_lit(kind)}")
    return f"CASE {' '.join(whens)} ELSE {_lit(DEFAULT_KIND)} END"


BELIEFS_TRIGGER = "trg_beliefs_source_kind"
SENSE_TRIGGER = "trg_sense_events_source_kind"


def beliefs_trigger_sql() -> str:
    return (
        f"CREATE TRIGGER IF NOT EXISTS {BELIEFS_TRIGGER} AFTER INSERT ON beliefs "
        "WHEN NEW.source_kind IS NULL BEGIN "
        # A verbatim copy inherits the stream of the earliest row that has one.
        "UPDATE beliefs SET source_stream = ("
        "SELECT p.source_stream FROM beliefs p WHERE p.content = NEW.content "
        "AND p.source_stream IS NOT NULL AND p.id != NEW.id ORDER BY p.id LIMIT 1) "
        "WHERE id = NEW.id AND source_stream IS NULL; "
        "UPDATE beliefs SET source_kind = CASE WHEN source_stream IS NOT NULL "
        f"THEN {stream_kind_sql('source_stream')} "
        f"ELSE {source_kind_sql('source')} END WHERE id = NEW.id; "
        "END"
    )


def sense_trigger_sql() -> str:
    return (
        f"CREATE TRIGGER IF NOT EXISTS {SENSE_TRIGGER} AFTER INSERT ON sense_events "
        "WHEN NEW.source_kind IS NULL BEGIN "
        f"UPDATE sense_events SET source_kind = {stream_kind_sql('NEW.stream')} "
        "WHERE id = NEW.id; END"
    )


def migrations() -> dict[str, list[str]]:
    """Additive DDL for init_db. The triggers are dropped and recreated on every
    init so they always carry the rules in this file."""
    return {
        "beliefs": [
            "ALTER TABLE beliefs ADD COLUMN source_stream TEXT",
            "ALTER TABLE beliefs ADD COLUMN source_kind TEXT",
            # Serves the trigger's inheritance lookup; only sense-derived rows.
            "CREATE INDEX IF NOT EXISTS idx_beliefs_stream_content "
            "ON beliefs(content) WHERE source_stream IS NOT NULL",
            f"DROP TRIGGER IF EXISTS {BELIEFS_TRIGGER}",
            beliefs_trigger_sql(),
        ],
        "sense": [
            "ALTER TABLE sense_events ADD COLUMN source_kind TEXT",
            f"DROP TRIGGER IF EXISTS {SENSE_TRIGGER}",
            sense_trigger_sql(),
        ],
    }
